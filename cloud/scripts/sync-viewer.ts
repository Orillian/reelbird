// Copies the viewer page template from the app (Sources/ReelbirdShare/ViewerPage.swift) into
// src/viewer-template.ts, so hosted links render the same page the app uploads to your own bucket.
// Run after changing the Swift template: bun scripts/sync-viewer.ts (a test fails until you do).
import { readFileSync, writeFileSync } from "node:fs";

export function swiftViewer() {
  const swift = readFileSync(new URL("../../Sources/ReelbirdShare/ViewerPage.swift", import.meta.url), "utf8");
  const pick = (re: RegExp, what: string) => {
    const m = swift.match(re);
    if (!m) throw new Error(`Couldn't find ${what} in ViewerPage.swift`);
    return m[1]!;
  };
  return {
    template: pick(/static let template = #"""\n([\s\S]*?)\n"""#/, "the template"),
    hlsURL: pick(/static let hlsURL = "([^"]+)"/, "hlsURL"),
    hlsIntegrity: pick(/static let hlsIntegrity = "([^"]+)"/, "hlsIntegrity"),
  };
}

export const generated = () => {
  const v = swiftViewer();
  return `// Generated by scripts/sync-viewer.ts from Sources/ReelbirdShare/ViewerPage.swift. Don't edit.
export const HLS_URL = ${JSON.stringify(v.hlsURL)};
export const HLS_SRI = ${JSON.stringify(v.hlsIntegrity)};
export const VIEWER_TEMPLATE = ${JSON.stringify(v.template)};
`;
};

export const out = new URL("../src/viewer-template.ts", import.meta.url);

if (import.meta.main) {
  writeFileSync(out, generated());
  console.log("Wrote src/viewer-template.ts");
}
